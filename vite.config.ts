import tailwindcss from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import crypto from 'crypto';
import fs from 'fs';
import path from 'path';
import {defineConfig} from 'vite';
import {VitePWA} from 'vite-plugin-pwa';

function getLocalAssetManifestEntries(): {url: string; revision: string}[] {
  const imagesDir = path.resolve(__dirname, 'src/assets/images');
  if (!fs.existsSync(imagesDir)) return [];
  const files = fs.readdirSync(imagesDir).filter((f) => /\.(png|jpe?g|webp|svg)$/i.test(f));
  return files.map((file) => {
    const buffer = fs.readFileSync(path.join(imagesDir, file));
    const revision = crypto.createHash('md5').update(buffer).digest('hex');
    return {
      url: `/src/assets/images/${file}`,
      revision,
    };
  });
}

